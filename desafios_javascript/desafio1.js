// Desafio 1 — FizzBuzz
// Percorre de 1 a 100 e imprime Fizz, Buzz, FizzBuzz ou o próprio número.

function fizzBuzz() {
  for (let i = 1; i <= 100; i++) {
    if (i % 3 === 0 && i % 5 === 0) {
      console.log("FizzBuzz");
    } else if (i % 3 === 0) {
      console.log("Fizz");
    } else if (i % 5 === 0) {
      console.log("Buzz");
    } else {
      console.log(i);
    }
  }
}
 
fizzBuzz();